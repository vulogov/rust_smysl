#!/usr/bin/env python3
"""S4 data sets (eval/s4-protocol.md §2): write eval/s4/sets.toml, once, before the detector exists.

Development: S3 naive patches, S3 run1 and run2 agent diffs, and every 2nd real commit in the
development range (0-based even positions, oldest first). Held-out: the other real commits in the range,
the commits after the S3 bases, and the agent runs of `harness.py run s4-heldout --arms control --reps 2`
(listed by name; they do not exist until that run).

A real commit's corpus is the S0 commits that are ancestors of its parent. Agent diffs and naive patches
use the S3 base. Development tooling; never part of the shipped tool.
"""

import json
import subprocess
import sys
import tomllib
from pathlib import Path

EVAL = Path(__file__).resolve().parent.parent
S3 = EVAL / "s3"
OUT = EVAL / "s4" / "sets.toml"
REG = tomllib.loads((S3 / "tasks.toml").read_text())
COMMITS = tomllib.loads((EVAL / "commits.toml").read_text())["commit"]
# The development range starts after the oldest S0 commit (checked 2026-09-17).
RANGE = {"smysl": "a18e230", "ucal": "8fdb9b3"}
AFTER_BASE = {"smysl": ("183be01", "c7bf5a3"), "ucal": ("425bb3a", "48dc1fd")}


def git(repo, *args):
    return subprocess.run(["git", "-C", str(EVAL / ".repos" / repo), *args],
                          check=True, capture_output=True, text=True).stdout.strip()


def full(repo, rev):
    return git(repo, "rev-parse", f"{rev}^{{commit}}")


def main():
    if OUT.exists() and "--force" not in sys.argv:
        sys.exit(f"{OUT} exists: the split is fixed once (pass --force only before any detector run)")
    s0 = {(c["repo"], full(c["repo"], c["sha"])) for c in COMMITS}
    lines = ["# S4 data sets (eval/s4-protocol.md §2), generated by sets.py before the detector existed.",
             "# kind: naive | agent | commit. contradicting: the task's prerequisite is broken (oracle or naive",
             "# patch); absent for real commits, whose flags the owner adjudicates. base: the corpus is the S0",
             "# commits that are ancestors of it (a real commit's parent).", "", "schema = 1", ""]

    def case(set_name, id_, repo, kind, base, source, task=None, contradicting=None):
        lines.append("[[case]]")
        lines.append(f'set = "{set_name}"')
        lines.append(f'id = "{id_}"')
        lines.append(f'repo = "{repo}"')
        lines.append(f'kind = "{kind}"')
        lines.append(f'base = "{base}"')
        lines.append(f'source = "{source}"')
        if task is not None:
            lines.append(f"task = {task}")
        if contradicting is not None:
            lines.append(f"contradicting = {'true' if contradicting else 'false'}")
        lines.append("")

    # Development: naive patches.
    for t in REG["task"]:
        n = t["n"]
        patch = next(p for p in (S3 / "validation" / "patches" / f"{n}-replacement.patch",
                                 S3 / "validation" / "patches" / f"{n}.patch") if p.exists())
        case("dev", f"naive-{n}", t["repo"], "naive", REG["repos"][t["repo"]]["base"],
             str(patch.relative_to(EVAL)), task=n, contradicting=True)

    # Development: S3 agent diffs with a non-empty change.
    for run in ("run1", "run2"):
        for score in sorted((S3 / "results" / run).glob("task-*/score.json")):
            r = json.loads(score.read_text())
            if r.get("diff_lines", 0) == 0:
                continue
            n = r["task"]
            repo = next(t["repo"] for t in REG["task"] if t["n"] == n)
            case("dev", f"{run}-{score.parent.name}", repo, "agent", REG["repos"][repo]["base"],
                 str((score.parent / "diff.patch").relative_to(EVAL)), task=n,
                 contradicting=r["oracle"] == "violated")

    # Real commits in the development range: even positions development, odd held-out.
    for repo, start in RANGE.items():
        base = REG["repos"][repo]["base"]
        shas = git(repo, "rev-list", "--no-merges", "--reverse", f"{start}..{base}").split()
        shas = [s for s in shas if (repo, s) not in s0]
        for i, sha in enumerate(shas):
            case("dev" if i % 2 == 0 else "heldout", f"commit-{repo}-{sha[:12]}", repo, "commit",
                 git(repo, "rev-parse", f"{sha}^"), sha)

    # Held-out: commits after the S3 bases.
    for repo, (a, b) in AFTER_BASE.items():
        for sha in git(repo, "rev-list", "--no-merges", "--reverse", f"{a}..{b}").split():
            case("heldout", f"commit-{repo}-{sha[:12]}", repo, "commit", git(repo, "rev-parse", f"{sha}^"), sha)

    # Held-out: agent runs still to be made (control arm, 2 repetitions).
    for t in REG["task"]:
        for rep in (1, 2):
            name = f"task-{t['n']}-control-r{rep}"
            case("heldout", f"s4-heldout-{name}", t["repo"], "agent", REG["repos"][t["repo"]]["base"],
                 f"s3/results/s4-heldout/{name}/diff.patch", task=t["n"])

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    text = OUT.read_text()
    for set_name in ("dev", "heldout"):
        for kind in ("naive", "agent", "commit"):
            print(f"{set_name:<8} {kind:<7} {text.count(f'set = \"{set_name}\"\nid = \"') and sum(1 for b in text.split('[[case]]') if f'set = \"{set_name}\"' in b and f'kind = \"{kind}\"' in b)}")


if __name__ == "__main__":
    main()
